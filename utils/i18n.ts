export const t = (key: string, language: Language = 'fr', params?: Record<string, any>): string => {
  const lang = normalizeLanguage(language);
  const frMap = TRANSLATIONS.fr;
  const enMap = TRANSLATIONS.en;
  let text =
    (lang === 'en' ? enMap[key] : frMap[key]) ||
    frMap[key] ||
    enMap[key];

  if (!text) {
    text = humanizeKey(key);
  }

  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      const val = String(v ?? '');
      const keyEsc = escapeRegExp(k);
      // Replace double braces first to avoid partial replacements inside `{{key}}`
      text = text.replace(new RegExp(`\\{\\{\\s*${keyEsc}\\s*\\}\\}`, 'g'), val);
      text = text.replace(new RegExp(`\\{\\s*${keyEsc}\\s*\\}`, 'g'), val);
    });
  }

  return text;
};
